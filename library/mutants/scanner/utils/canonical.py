"""
Canonical library- and sources-tree file discovery.

Single authoritative place that knows how to walk the audiobook trees. Every
consumer that previously ran its own ``rglob`` with per-call exclusions
(incremental adder, full rescan, conversion-progress counter, checksum
collector, ASIN backfill, cover embedder, corruption reporter) MUST use one of
the iterators here instead of re-implementing the filtering — forgetting one
exclusion at one call site caused silent failures (Audiobook-Manager-94p,
Audiobook-Manager-2sw). Audiobook-Manager-6cx consolidated the audio-file
walks here; Audiobook-Manager-fud finished the job — the Sources walks, the
``chapters.json`` sidecar walk, the corruption report and the cover embedder
were still open-coded, and nothing stopped a tenth one being written.

Two trees, two entry points:

- ``iter_library_files`` — the Library tree. Applies the canonicality rules
  below **by default**, so a new call site that simply calls it is correct
  without having to remember anything. A caller that genuinely wants the
  unfiltered walk must say so explicitly (``exclude_cover_art=False`` /
  ``exclude_translated=False``), which makes the deviation visible at the call
  site and reviewable in a diff. ``iter_canonical_audiobook_files`` is the
  audio-file-shaped wrapper over it.
- ``iter_source_files`` — the Sources tree (``.aaxc`` originals and their
  sidecars). No canonicality rules apply there; the value is a single
  definition of "recursive, missing directory yields nothing".

A *canonical* audiobook file is an audio file that is:

- NOT a ``.cover.<ext>`` cover-art sidecar (see ``is_cover_art_file``)
- NOT under a ``translated/`` subdirectory — those are per-chapter
  translation artifacts (e.g. ``Book.ch001.zh-Hans.opus``) generated by the
  chapter-translation pipeline and regenerable from the canonical source.
  Only directories NAMED ``translated`` are excluded (``Path.parts``
  membership, not substring match), so a book titled "The Translated
  Soldier" is still ingested.
"""

from collections.abc import Iterator, Sequence
from pathlib import Path
from typing import NewType

from .constants import SUPPORTED_FORMATS, is_cover_art_file

# Nominal type for paths that have passed canonicality filtering. Consumers
# can annotate with this to make "already filtered" explicit at type level.
CanonicalAudiobookPath = NewType("CanonicalAudiobookPath", Path)

# Directory name whose contents are per-chapter translation artifacts.
TRANSLATED_DIR_NAME = "translated"

# Default glob for the Sources tree: Audible originals.
SOURCE_FILE_PATTERNS: tuple[str, ...] = ("*.aaxc",)


def is_canonical_audiobook_file(path: Path) -> bool:
    """Return True if ``path`` is a canonical audiobook file (not a cover-art
    sidecar and not a translated/ chapter artifact)."""
    return not is_cover_art_file(path) and TRANSLATED_DIR_NAME not in path.parts


def iter_library_files(
    library_dir: Path,
    patterns: Sequence[str],
    *,
    exclude_cover_art: bool = True,
    exclude_translated: bool = True,
) -> Iterator[Path]:
    """Recursively iterate files under ``library_dir`` matching ``patterns``.

    This is the only place in the tree that should call ``rglob`` on a library
    root (enforced by ``tests/test_source_guards.py``).

    Args:
        library_dir: Root of the library tree. A nonexistent directory yields
            nothing (no error) — every former call site either guarded with
            ``.exists()`` or relied on ``rglob`` returning empty, and the
            behaviour is now uniform.
        patterns: ``rglob`` patterns, e.g. ``("*.opus",)`` or
            ``("chapters.json",)``. Iteration is pattern-major: every match of
            the first pattern, then the second, and so on. A path matching two
            patterns is yielded twice — same as chaining ``rglob`` calls.
        exclude_cover_art: Skip ``<title>.cover.<ext>`` sidecars. Default True.
        exclude_translated: Skip anything under a directory named
            ``translated/``. Default True.

    Yields:
        Matching paths, in ``rglob`` order within each pattern.
    """
    if not library_dir.exists():
        return
    for pattern in patterns:
        for path in library_dir.rglob(pattern):
            if exclude_cover_art and is_cover_art_file(path):
                continue
            if exclude_translated and TRANSLATED_DIR_NAME in path.parts:
                continue
            yield path


def iter_canonical_audiobook_files(
    library_dir: Path, formats: Sequence[str] | None = None
) -> Iterator[CanonicalAudiobookPath]:
    """Iterate canonical audiobook files under ``library_dir``.

    Thin, audio-shaped wrapper over ``iter_library_files`` — turns a list of
    extensions into globs and applies both canonicality exclusions.

    Args:
        library_dir: Root of the library tree to scan. A nonexistent
            directory yields nothing (no error).
        formats: Extensions to include (e.g. ``[".opus"]``). Defaults to
            ``SUPPORTED_FORMATS``. Iteration is format-major: all files of
            the first extension, then the second, and so on.

    Yields:
        Paths to canonical audiobook files — cover-art sidecars and
        ``translated/`` chapter artifacts are excluded.
    """
    if formats is None:
        formats = SUPPORTED_FORMATS
    for path in iter_library_files(library_dir, [f"*{ext}" for ext in formats]):
        yield CanonicalAudiobookPath(path)


def iter_source_files(
    sources_dir: Path, patterns: Sequence[str] = SOURCE_FILE_PATTERNS
) -> Iterator[Path]:
    """Recursively iterate files under the Sources tree matching ``patterns``.

    The Sources tree holds Audible originals; none of the Library
    canonicality rules apply to it (there are no cover-art sidecars or
    ``translated/`` artifacts there). This exists so "how do we enumerate
    sources" has one answer, including the nonexistent-directory case that
    every former call site spelled out for itself.

    Args:
        sources_dir: Root of the Sources tree. Nonexistent yields nothing.
        patterns: ``rglob`` patterns. Defaults to ``("*.aaxc",)``.

    Yields:
        Matching paths, in ``rglob`` order within each pattern.
    """
    if not sources_dir.exists():
        return
    for pattern in patterns:
        yield from sources_dir.rglob(pattern)
