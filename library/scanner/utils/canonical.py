"""
Canonical audiobook file discovery.

Single authoritative iterator for enumerating canonical audiobook files in a
library tree. Every consumer that previously ran its own ``rglob`` with
per-call exclusions (incremental adder, full rescan, conversion-progress
counter, checksum collector) MUST use this iterator instead of re-implementing
the filtering — forgetting one exclusion at one call site caused silent
failures (Audiobook-Manager-94p, Audiobook-Manager-2sw). See
Audiobook-Manager-6cx for the consolidation rationale.

A *canonical* audiobook file is an audio file that is:

- NOT a ``.cover.<ext>`` cover-art sidecar (see ``is_cover_art_file``)
- NOT under a ``translated/`` subdirectory — those are per-chapter
  translation artifacts (e.g. ``Book.ch001.zh-Hans.opus``) generated by the
  chapter-translation pipeline and regenerable from the canonical source.
  Only directories NAMED ``translated`` are excluded (``Path.parts``
  membership, not substring match), so a book titled "The Translated
  Soldier" is still ingested.
"""

from collections.abc import Iterator, Sequence
from pathlib import Path
from typing import NewType

from .constants import SUPPORTED_FORMATS, is_cover_art_file

# Nominal type for paths that have passed canonicality filtering. Consumers
# can annotate with this to make "already filtered" explicit at type level.
CanonicalAudiobookPath = NewType("CanonicalAudiobookPath", Path)

# Directory name whose contents are per-chapter translation artifacts.
TRANSLATED_DIR_NAME = "translated"


def is_canonical_audiobook_file(path: Path) -> bool:
    """Return True if ``path`` is a canonical audiobook file (not a cover-art
    sidecar and not a translated/ chapter artifact)."""
    return not is_cover_art_file(path) and TRANSLATED_DIR_NAME not in path.parts


def iter_canonical_audiobook_files(
    library_dir: Path, formats: Sequence[str] | None = None
) -> Iterator[CanonicalAudiobookPath]:
    """Iterate canonical audiobook files under ``library_dir``.

    Args:
        library_dir: Root of the library tree to scan. A nonexistent
            directory yields nothing (no error).
        formats: Extensions to include (e.g. ``[".opus"]``). Defaults to
            ``SUPPORTED_FORMATS``. Iteration is format-major: all files of
            the first extension, then the second, and so on.

    Yields:
        Paths to canonical audiobook files — cover-art sidecars and
        ``translated/`` chapter artifacts are excluded.
    """
    if formats is None:
        formats = SUPPORTED_FORMATS
    if not library_dir.exists():
        return
    for ext in formats:
        for f in library_dir.rglob(f"*{ext}"):
            if is_canonical_audiobook_file(f):
                yield CanonicalAudiobookPath(f)
